"""Run the whole AgentReady loop on a temporary copy and export the evidence.

    python3 scripts/run_full_loop.py     # -> docs/examples/SUMMARY.md and results.json
"""
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["AGENTREADY_VAR"] = tempfile.mkdtemp(prefix="agentready-loop-")

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402

OUT = ROOT / "docs" / "examples"
PLAN = {
    "billing-service": ["1-architecture-doc", "2-env-name-only", "3-env-working-config"],
    "notifications-service": ["1-catalog-entry", "2-openapi", "3-test-command"],
}


def row(step, data, check_id=None):
    run = data["latest_run"]
    finding = next((f for f in data["findings"] if f["check_id"] == check_id), None)
    return {
        "step": step, "score": data["score"], "task": run["status"],
        "blocked_at": run["blocked_dimension"], "blocked_check": run["blocked_check"],
        "finding_status": finding["status"] if finding else None,
    }


def main():
    results = {"services": {}}
    with TestClient(app) as client:
        client.post("/api/demo/reset")
        results["baseline"] = client.get("/api/overview").json()
        for service in ("billing-service", "notifications-service", "identity-service"):
            data = client.get(f"/api/services/{service}").json()
            rows = [row("Baseline", data)]
            for fix_id in PLAN.get(service, []):
                client.post(f"/api/services/{service}/fixes/{fix_id}/apply")
                data = client.post(f"/api/services/{service}/assess").json()
                fix = next(f for f in data["fixes"] if f["id"] == fix_id)
                rows.append(row(fix["title"], data, fix["check_id"]))
            results["services"][service] = rows
        results["final"] = client.get("/api/overview").json()

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "results.json").write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")

    lines = ["# AgentReady: evidence from a full run", "",
             "Generated by `python3 scripts/run_full_loop.py`. Sample repositories are fictional and deliberately flawed. "
             "Task outcomes come from the scripted probe, not an LLM.", ""]
    for service, rows in results["services"].items():
        lines += [f"## {service}", "", "| Step | Score | Task | Blocked at | Targeted finding |", "|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r['step']} | {r['score']} | {r['task']} | {r['blocked_at'] or '—'} | {r['finding_status'] or '—'} |")
        lines.append("")
    base, final = results["baseline"], results["final"]
    lines += ["## Portfolio", "", "| | Baseline | Final |", "|---|---|---|",
              f"| Tasks completed | {base['completion']['latest']['completed']} of {base['completion']['latest']['total']} "
              f"| {final['completion']['latest']['completed']} of {final['completion']['latest']['total']} |",
              f"| Average score | {base['score']['latest']} | {final['score']['latest']} |",
              f"| Tasks blocked | {base['repeat_failures']['latest']} | {final['repeat_failures']['latest']} |",
              f"| Findings open | {base['findings']['open']} | {final['findings']['open']} |",
              f"| Findings verified | {base['findings']['verified']} | {final['findings']['verified']} |",
              f"| Findings reopened at least once | {base['findings']['reopened']} | {final['findings']['reopened']} |", ""]
    (OUT / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
